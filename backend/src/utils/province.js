/**
 * แปลงชื่อจังหวัดที่ผู้ใช้กรอกมาให้เป็นชื่อมาตรฐาน
 * ตัดช่องว่าง / คำนำหน้า "จังหวัด" "จ." / จุดกับไม้ยมกท้ายคำ แล้วเทียบกับชื่อย่อที่รู้จัก
 * คืน '' ถ้าไม่ใช่จังหวัดจริง (ใช้ตรวจตอนนำเข้า Excel ได้เลย)
 */
function canonicalProvince(raw) {
  let s = String(raw || '').replace(/\s+/g, '');
  if (!s) return '';
  s = s.replace(/^(จังหวัด|จ\.)/, '');
  s = s.replace(/[.ฯ]+$/, '');
  s = PROVINCE_ALIASES[s] || s;
  return REGION_MAP[s] ? s : '';
}

/**
 * หาภูมิภาคจากชื่อจังหวัด — ใช้กับข้อมูลที่อยู่ในฐานข้อมูลแล้ว จึงผ่อนปรนกว่า
 * ถ้าเทียบตรงๆ ไม่ได้ จะเผื่อกรณีกรอกที่อยู่มาทั้งก้อน เช่น "เขตบางรัก กรุงเทพมหานคร"
 */
function getRegion(raw) {
  const exact = canonicalProvince(raw);
  if (exact) return REGION_MAP[exact];

  const s = String(raw || '').replace(/\s+/g, '');
  if (!s) return 'ไม่ระบุ';
  // ที่อยู่ภาษาไทยลงท้ายด้วยจังหวัด — เทียบจากชื่อยาวสุดก่อน กัน "นครพนม" ไปชนกับ "พนม"
  const hit = PROVINCE_NAMES
    .filter((k) => s.endsWith(k))
    .sort((a, b) => b.length - a.length)[0];
  return hit ? REGION_MAP[hit] : 'อื่นๆ';
}

