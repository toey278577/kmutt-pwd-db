const PROVINCE_SET = new Set(THAI_PROVINCES);

/**
 * แปลงชื่อจังหวัดที่กรอกมาให้เป็นชื่อมาตรฐาน
 * ตัดช่องว่าง / คำนำหน้า "จังหวัด" "จ." / จุดกับไม้ยมกท้ายคำ แล้วเทียบกับชื่อย่อที่รู้จัก
 * คืน '' ถ้าไม่ใช่จังหวัดจริง
 */
export function canonicalProvince(raw) {
  let s = String(raw || '').replace(/\s+/g, '');
  if (!s) return '';
  s = s.replace(/^(จังหวัด|จ\.)/, '');
  s = s.replace(/[.ฯ]+$/, '');
  s = PROVINCE_ALIASES[s] || s;
  return PROVINCE_SET.has(s) ? s : '';
}

/**
 * ตรวจชื่อจังหวัดหนึ่งช่อง คืนสถานะไว้โชว์ตอนนำเข้า Excel
 *   ok    = ตรงอยู่แล้ว
 *   fixed = แก้ให้อัตโนมัติ (เช่น "กทม." → "กรุงเทพมหานคร")
 *   empty = ไม่ได้กรอก
 *   bad   = ไม่รู้จักจังหวัดนี้ → ห้ามนำเข้า
 */
export function checkProvince(raw) {
  const typed = String(raw || '').trim();
  if (!typed) return { status: 'empty', typed, value: '' };
  const canon = canonicalProvince(typed);
  if (!canon) return { status: 'bad', typed, value: typed };
  return { status: canon === typed ? 'ok' : 'fixed', typed, value: canon };
}
